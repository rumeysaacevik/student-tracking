    private void w_stuLogInActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_w_stuLogInActionPerformed
        String sql = "SELECT * FROM students WHERE username = ? AND password = ?";

        try {
            PreparedStatement preparedStatement = con.prepareStatement(sql);
            preparedStatement.setString(1, w_studentEntry.getText());
            preparedStatement.setString(2, w_studentPassword.getText());

            ResultSet resultSet = preparedStatement.executeQuery();

            if (resultSet.next()) {

                JOptionPane.showMessageDialog(this, "Welcome, " + resultSet.getString("name") + "!", "Login Successful", JOptionPane.INFORMATION_MESSAGE);

                setVisible(false);
                studentLogin login = new studentLogin();
                login.setVisible(true);
            } else {

                JOptionPane.showMessageDialog(this, "No record found. Please enter a valid username and password.", "Error", JOptionPane.ERROR_MESSAGE);
            }

        } catch (SQLException ex) {
            Logger.getLogger(homePage.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_w_stuLogInActionPerformed

