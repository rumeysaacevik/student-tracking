    private String getStaffName(String username) {
        String sql = "SELECT name FROM instructors WHERE username = ?";
        try {
            PreparedStatement preparedStatement = con.prepareStatement(sql);
            preparedStatement.setString(1, username);
            ResultSet resultSet = preparedStatement.executeQuery();

            if (resultSet.next()) {
                return resultSet.getString("name");
            }
        } catch (SQLException ex) {
            Logger.getLogger(homePage.class.getName()).log(Level.SEVERE, null, ex);
        }

        return ""; // Eğer ad alınamazsa boş bir string döndür
    }

// Öğretmen girişini kontrol etmek için fonksiyon
    private boolean isValidStaff(String username, String password) {
        String sql = "SELECT * FROM instructors WHERE username = ? AND password = ?";
        try {
            PreparedStatement preparedStatement = con.prepareStatement(sql);
            preparedStatement.setString(1, username);
            preparedStatement.setString(2, password);
            ResultSet resultSet = preparedStatement.executeQuery();

            return resultSet.next(); // Eğer sonuç varsa, öğretmen geçerli demektir
        } catch (SQLException ex) {
            Logger.getLogger(homePage.class.getName()).log(Level.SEVERE, null, ex);
        }

        return false; // Eğer bir hata olursa ya da sonuç yoksa geçerli değildir
    }

